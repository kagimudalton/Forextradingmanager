async function loadScanner() {
  const body = document.getElementById("scanner-body");
  body.innerHTML = `<tr><td colspan="6" class="empty-state">Scanning…</td></tr>`;
  try {
    const rows = await api.scanner();
    if (!rows.length) {
      body.innerHTML = `<tr><td colspan="6" class="empty-state">No data.</td></tr>`;
      return;
    }
    body.innerHTML = rows.map((r) => `
      <tr>
        <td><strong>${r.symbol}</strong></td>
        <td>${r.price ?? "—"}</td>
        <td class="${r.change_pct >= 0 ? "up" : "down"}">${r.change_pct >= 0 ? "+" : ""}${r.change_pct}%</td>
        <td><span class="opp-dir ${r.direction}">${r.direction}</span></td>
        <td>
          <div style="display:flex;align-items:center;gap:10px;">
            <div class="confidence-bar-track" style="width:80px"><div class="confidence-bar-fill" style="width:${r.confidence}%"></div></div>
            <span class="confidence-pct">${r.confidence}%</span>
          </div>
        </td>
        <td><span class="tag ${r.risk}">${r.risk}</span></td>
      </tr>
    `).join("");
  } catch (err) {
    body.innerHTML = `<tr><td colspan="6" class="empty-state">Failed to scan markets.</td></tr>`;
  }
}

