document.addEventListener("DOMContentLoaded", async () => {
  const user = await initShell("dashboard");
  if (!user) return;

  wireNav();
  wireButtons();
  connectWebSocket(handleWsMessage);
  await loadSettingsForCaps();

  const initialView = (location.hash || "#overview").replace("#", "");
  switchView(VIEW_META[initialView] ? initialView : "overview");
});

function wireNav() {
  document.querySelectorAll(".nav-link[data-view]").forEach((el) => {
    el.addEventListener("click", (e) => {
      e.preventDefault();
      history.replaceState(null, "", `#${el.dataset.view}`);
      switchView(el.dataset.view);
    });
  });
}

function switchView(view) {
  currentView = view;
  document.querySelectorAll(".view").forEach((el) => (el.hidden = true));
  document.getElementById(`view-${view}`).hidden = false;
  document.querySelectorAll(".nav-link").forEach((el) => el.classList.toggle("active", el.dataset.view === view));

  const meta = VIEW_META[view];
  document.getElementById("view-heading").textContent =
    view === "overview" && window.__username ? `Welcome, ${window.__username}` : meta.heading;
  document.getElementById("view-subheading").textContent = meta.sub;

  loadViewData(view);
}

async function loadViewData(view) {
  switch (view) {
    case "overview":  await Promise.all([loadAccount(), loadPositions(), loadRiskStatus(), loadSignals(), loadBotStatus()]); break;
    case "scanner":   await loadScanner(); break;
    case "signals":   await loadSignalHistory(); break;
    case "portfolio": await loadPortfolio(); break;
    case "risk":      await loadRiskDetail(); break;
    case "reports":   await loadReports(); break;
    case "analyst":   /* runs on demand via button, nothing to preload */ break;
    case "calculator":/* runs on demand via form submit */ break;
    case "journal":   await loadJournal(); break;
    case "calendar":  await loadCalendar(); break;
    case "backtest":  /* runs on demand via form submit */ break;
  }
}

async function loadSettingsForCaps() {
  try {
    currentSettings = await api.getSettings();
    const el = document.getElementById("stat-max-trades");
    if (el) el.textContent = currentSettings.max_trades;
  } catch (_) {}
}

async function loadAccount() {
  try {
    const acct = await api.account();
    document.getElementById("stat-balance").textContent = fmtMoney(acct.balance);
    document.getElementById("stat-equity").textContent = fmtMoney(acct.equity);
    document.getElementById("stat-currency").textContent = acct.currency;
    document.getElementById("stat-margin-level").textContent = fmtPct(acct.margin_level);

    const dot = document.getElementById("mt5-dot");
    const text = document.getElementById("mt5-text");
    dot.classList.add("on"); dot.classList.remove("off");
    text.textContent = acct.mock ? "MT5 · Mock data" : `MT5 · ${acct.server}`;
  } catch (err) { showToast(err.message, "error"); }
}

async function loadPositions() {
  const body = document.getElementById("positions-body");
  try {
    const positions = await api.positions();
    document.getElementById("stat-open-trades").textContent = positions.length;

    const dailyProfit = positions.reduce((sum, p) => sum + p.profit, 0);
    const sub = document.getElementById("stat-daily-profit");
    sub.textContent = fmtMoney(dailyProfit);
    sub.className = `stat-value ${dailyProfit >= 0 ? "up" : "down"}`;
    document.getElementById("stat-daily-profit-sub").textContent = `${positions.length} open position(s)`;

    body.innerHTML = renderPositionsRows(positions, true);
    wireCloseButtons(body);
  } catch (_) {
    body.innerHTML = `<tr><td colspan="7" class="empty-state">Failed to load positions.</td></tr>`;
  }
}

function renderPositionsRows(positions, withClose) {
  if (!positions.length) return `<tr><td colspan="7" class="empty-state">No open positions.</td></tr>`;
  return positions.map((p) => `
    <tr>
      <td><strong>${p.symbol}</strong></td>
      <td><span class="opp-dir ${p.type}">${p.type}</span></td>
      <td>${p.volume}</td>
      <td>${p.open_price}</td>
      <td>${p.current_price}</td>
      <td class="${p.profit >= 0 ? "up" : "down"}">${fmtMoney(p.profit)}</td>
      <td>${withClose ? `<button class="btn btn-ghost" data-close-ticket="${p.ticket}">Close</button>` : ""}</td>
    </tr>
  `).join("");
}

function wireCloseButtons(container) {
  container.querySelectorAll("[data-close-ticket]").forEach((btn) => {
    btn.addEventListener("click", () => closeTrade(Number(btn.dataset.closeTicket)));
  });
}

