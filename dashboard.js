async function loadPortfolio() {
  try {
    const [acct, positions, history] = await Promise.all([
      api.account(), api.positions(), api.history(30),
    ]);

    document.getElementById("pf-balance").textContent = fmtMoney(acct.balance);
    document.getElementById("pf-equity").textContent = fmtMoney(acct.equity);
    document.getElementById("pf-margin").textContent = fmtMoney(acct.free_margin);
    document.getElementById("pf-leverage").textContent = `1:${acct.leverage}`;

    const posBody = document.getElementById("pf-positions-body");
    posBody.innerHTML = renderPositionsRows(positions, true);
    wireCloseButtons(posBody);

    const histBody = document.getElementById("pf-history-body");
    if (!history.length) {
      histBody.innerHTML = `<tr><td colspan="5" class="empty-state">No trade history yet.</td></tr>`;
    } else {
      histBody.innerHTML = history.map((h) => `
        <tr>
          <td><strong>${h.symbol}</strong></td>
          <td><span class="opp-dir ${h.type}">${h.type}</span></td>
          <td>${h.volume}</td>
          <td class="${h.profit >= 0 ? "up" : "down"}">${fmtMoney(h.profit)}</td>
          <td class="muted">${h.closed_at}</td>
        </tr>
      `).join("");
    }
  } catch (err) {
    showToast(err.message, "error");
  }
}

