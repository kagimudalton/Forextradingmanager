/* dashboard.js — powers dashboard.html: tabbed workspace (Overview, Market
   Scanner, AI Signals, Portfolio, Risk Manager, Reports), AI control center,
   live WebSocket updates including auto-trading bot activity. */

let currentSettings = { max_trades: 5 };
let currentView = "overview";

const VIEW_META = {
  overview:  { heading: "Welcome",         sub: "Live account snapshot & AI market intelligence" },
  scanner:   { heading: "Market Scanner",  sub: "Live confidence scan across the broader instrument universe" },
  signals:   { heading: "AI Signals",      sub: "Signal history generated by the analysis engine" },
  portfolio: { heading: "Portfolio",       sub: "Account balance, open positions, and trade history" },
  risk:      { heading: "Risk Manager",    sub: "Exposure, drawdown, and position sizing controls" },
  reports:   { heading: "Reports",         sub: "Performance breakdown across all closed trades" },
};

document.addEventListener("DOMContentLoaded", async () => {
  const user = await initShell("dashboard");
  if (!user) return;

  wireNav();
  wireButtons();
  connectWebSocket(handleWsMessage);

  await loadSettingsForCaps();

  const initialView = (location.hash || "#overview").replace("#", "");
  switchView(VIEW_META[initialView] ? initialView : "overview", user);
});

/* ---------------------------------------------------------------------- */
/* View switching                                                          */
/* ---------------------------------------------------------------------- */

function wireNav() {
  document.querySelectorAll(".nav-link[data-view]").forEach((el) => {
    el.addEventListener("click", (e) => {
      e.preventDefault();
      const view = el.dataset.view;
      history.replaceState(null, "", `#${view}`);
      switchView(view);
    });
  });
}

function switchView(view) {
  currentView = view;

  document.querySelectorAll(".view").forEach((el) => (el.hidden = true));
  document.getElementById(`view-${view}`).hidden = false;

  document.querySelectorAll(".nav-link").forEach((el) => {
    el.classList.toggle("active", el.dataset.view === view);
  });

  const meta = VIEW_META[view];
  document.getElementById("view-heading").textContent =
    view === "overview" && window.__username ? `Welcome, ${window.__username}` : meta.heading;
  document.getElementById("view-subheading").textContent = meta.sub;

  loadViewData(view);
}

async function loadViewData(view) {
  switch (view) {
    case "overview":
      await Promise.all([loadAccount(), loadPositions(), loadRiskStatus(), loadSignals(), loadBotStatus()]);
      break;
    case "scanner":
      await loadScanner();
      break;
    case "signals":
      await loadSignalHistory();
      break;
    case "portfolio":
      await loadPortfolio();
      break;
    case "risk":
      await loadRiskDetail();
      break;
    case "reports":
      await loadReports();
      break;
  }
}

