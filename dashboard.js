async function loadReports() {
  try {
    const [summary, trades] = await Promise.all([
      api.reportsSummary(), api.reportsTrades(50),
    ]);

    document.getElementById("rp-pnl").textContent = fmtMoney(summary.total_pnl);
    document.getElementById("rp-pnl").className = `stat-value ${summary.total_pnl >= 0 ? "up" : "down"}`;
    document.getElementById("rp-winrate").textContent = fmtPct(summary.win_rate);
    document.getElementById("rp-best").textContent = fmtMoney(summary.best_trade);
    document.getElementById("rp-worst").textContent = fmtMoney(summary.worst_trade);

    const bySymbolCard = document.getElementById("rp-by-symbol");
    if (!summary.by_symbol.length) {
      bySymbolCard.innerHTML = `<div class="empty-state">No closed trades yet.</div>`;
    } else {
      bySymbolCard.innerHTML = summary.by_symbol.map((s) => `
        <div class="opp-row">
          <span><strong>${s.symbol}</strong> <span class="muted">(${s.trades} trades)</span></span>
          <span class="${s.pnl >= 0 ? "up" : "down"}">${fmtMoney(s.pnl)}</span>
        </div>
      `).join("");
    }

    const tradesBody = document.getElementById("rp-trades-body");
    if (!trades.length) {
      tradesBody.innerHTML = `<tr><td colspan="4" class="empty-state">No trades yet.</td></tr>`;
    } else {
      tradesBody.innerHTML = trades.map((t) => `
        <tr>
          <td><strong>${t.symbol}</strong></td>
          <td><span class="opp-dir ${t.type}">${t.type}</span></td>
          <td class="${(t.profit || 0) >= 0 ? "up" : "down"}">${t.profit !== null ? fmtMoney(t.profit) : "—"}</td>
          <td><span class="tag ${t.status === "OPEN" ? "MEDIUM" : "LOW"}">${t.status}</span></td>
        </tr>
      `).join("");
    }
  } catch (err) {
    showToast(err.message, "error");
  }
}

/* ---------------------------------------------------------------------- */
/* WebSocket events                                                         */
/* ---------------------------------------------------------------------- */

function handleWsMessage(msg) {
  switch (msg.event) {
    case "trade_opened":
    case "trade_closed":
      if (currentView === "overview") { loadPositions(); loadRiskStatus(); }
      if (currentView === "portfolio") loadPortfolio();
      break;
    case "bot_trade":
      showToast(
        `🤖 Bot opened ${msg.data.type} ${msg.data.symbol} (${msg.data.confidence}% confidence)`,
        "success"
      );
      if (currentView === "overview") { loadPositions(); loadRiskStatus(); }
      if (currentView === "portfolio") loadPortfolio();
      break;
    case "analysis_complete":
      if (currentView === "overview") renderOpportunities(msg.data);
      break;
    case "bot_status":
      setBotStatusLine(msg.data.running);
      break;
    case "price_update":
      // Reserved for a future live ticker on the scanner view.
      break;
  }
}
