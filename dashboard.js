async function runAnalyst() {
  const symbolInput = document.getElementById("analyst-symbol");
  const symbol = symbolInput.value.trim().toUpperCase();
  const card = document.getElementById("analyst-result");
  const btn = document.getElementById("btn-analyst-run");
  if (!symbol) return;

  btn.disabled = true; btn.textContent = "Analyzing…";
  card.innerHTML = `<div class="empty-state">Analyzing ${symbol}…</div>`;
  try {
    const result = await api.marketAnalyst(symbol);
    card.innerHTML = `
      <div class="opp-row"><span class="muted">Trend</span><strong>${result.trend}</strong></div>
      <div class="opp-row"><span class="muted">RSI</span><strong>${result.rsi}</strong></div>
      <div class="opp-row"><span class="muted">Support / Resistance</span><strong>${result.support ?? "—"} / ${result.resistance ?? "—"}</strong></div>
      <div class="opp-row"><span class="muted">Confidence</span><strong>${result.confidence}%</strong></div>
      <p style="margin-top:16px;line-height:1.6">${result.summary}</p>
      <p class="muted" style="margin-top:14px;font-size:12px">${result.disclaimer}</p>
    `;
  } catch (err) {
    card.innerHTML = `<div class="empty-state">Failed to analyze ${symbol}: ${err.message}</div>`;
  } finally {
    btn.disabled = false; btn.textContent = "Analyze";
  }
}

