async function loadSignals() {
  try { renderOpportunities(await api.signals(6)); } catch (_) {}
}

function renderOpportunities(signals) {
  const card = document.getElementById("opportunities-card");
  if (!signals.length) {
    card.innerHTML = `<div class="empty-state">Run <strong>Analyze Markets</strong> to generate AI signals.</div>`;
    return;
  }
  card.innerHTML = signals.map((s) => `
    <div class="opp-row">
      <div class="opp-symbol">${s.symbol} <span class="opp-dir ${s.direction}">${s.direction}</span></div>
      <div style="display:flex;align-items:center;gap:10px;">
        <div class="confidence-bar-track"><div class="confidence-bar-fill" style="width:${s.confidence}%"></div></div>
        <span class="confidence-pct">${s.confidence}%</span>
      </div>
    </div>
  `).join("");
}

async function loadBotStatus() {
  try { setBotStatusLine((await api.botStatus()).running); } catch (_) {}
}

function setBotStatusLine(running) {
  const el = document.getElementById("bot-status-line");
  if (el) el.textContent = `Bot status: ${running ? "🟢 Running (Auto Mode) — checks every ~45s" : "⚪ Stopped"}`;
}

function wireButtons() {
  document.getElementById("btn-analyze").addEventListener("click", runAnalysis);
  document.getElementById("btn-generate").addEventListener("click", runAnalysis);

  const signalsGenBtn = document.getElementById("btn-signals-generate");
  if (signalsGenBtn) signalsGenBtn.addEventListener("click", async () => { await runAnalysis(); await loadSignalHistory(); });

  const rescanBtn = document.getElementById("btn-rescan");
  if (rescanBtn) rescanBtn.addEventListener("click", loadScanner);

  const analystBtn = document.getElementById("btn-analyst-run");
  if (analystBtn) analystBtn.addEventListener("click", runAnalyst);

  const calcForm = document.getElementById("calc-form");
  if (calcForm) calcForm.addEventListener("submit", runRiskCalculator);

  const btForm = document.getElementById("bt-form");
  if (btForm) btForm.addEventListener("submit", runBacktest);

  document.getElementById("btn-start-bot").addEventListener("click", async (e) => {
    e.target.disabled = true;
    try {
      setBotStatusLine((await api.botStart()).running);
      showToast("Auto mode started — bot will trade on high-confidence signals", "success");
    } catch (err) { showToast(err.message, "error"); }
    finally { e.target.disabled = false; }
  });

  document.getElementById("btn-stop-bot").addEventListener("click", async (e) => {
    e.target.disabled = true;
    try {
      setBotStatusLine((await api.botStop()).running);
      showToast("Bot stopped", "success");
    } catch (err) { showToast(err.message, "error"); }
    finally { e.target.disabled = false; }
  });
}

async function runAnalysis() {
  const btn = document.getElementById("btn-analyze");
  const btn2 = document.getElementById("btn-generate");
  if (btn) { btn.disabled = true; btn.textContent = "🔍 Analyzing…"; }
  if (btn2) btn2.disabled = true;
  try {
    const results = await api.analyze();
    renderOpportunities(results);
    if (currentView === "overview") await loadPositions();
    showToast(`Analysis complete — ${results.length} symbols scanned`, "success");
  } catch (err) { showToast(err.message, "error"); }
  finally {
    if (btn) { btn.disabled = false; btn.textContent = "🔍 Analyze Markets"; }
    if (btn2) btn2.disabled = false;
  }
}

