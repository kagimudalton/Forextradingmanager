async function loadSignalHistory() {
  const body = document.getElementById("signals-body");
  try {
    const signals = await api.signals(30);
    if (!signals.length) {
      body.innerHTML = `<tr><td colspan="6" class="empty-state">No signals yet — click Generate New Signals.</td></tr>`;
      return;
    }
    body.innerHTML = signals.map((s) => `
      <tr>
        <td class="muted">${s.created_at}</td>
        <td><strong>${s.symbol}</strong></td>
        <td><span class="opp-dir ${s.direction}">${s.direction}</span></td>
        <td>${s.confidence}%</td>
        <td><span class="tag ${s.risk}">${s.risk}</span></td>
        <td class="muted">${(s.reason || []).join(", ")}</td>
      </tr>
    `).join("");
  } catch (err) {
    body.innerHTML = `<tr><td colspan="6" class="empty-state">Failed to load signal history.</td></tr>`;
  }
}

